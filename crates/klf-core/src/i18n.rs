//! Interface texts in Hebrew, French and English (compiled in: no external translation file).

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    He,
    Fr,
    En,
}

impl Lang {
    /// From a Windows LANGID (GetUserDefaultUILanguage): primary language in the low 10 bits.
    pub fn from_langid(langid: u16) -> Lang {
        match langid & 0x3FF {
            0x0D => Lang::He,
            0x0C => Lang::Fr,
            _ => Lang::En,
        }
    }
    pub fn is_rtl(self) -> bool {
        self == Lang::He
    }
}

