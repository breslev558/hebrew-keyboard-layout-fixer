pub fn text_with_key(lang: Lang, m: Msg, key: &str) -> String {
    text(lang, m).replace("{key}", key)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_text_exists_and_is_short_enough() {
        for l in [Lang::He, Lang::Fr, Lang::En] {
            for m in ALL_MSGS {
                let t = text(l, *m);
                assert!(!t.is_empty(), "{l:?} {m:?}");
                // NotifyIcon tooltip limit: 127 characters
                if matches!(m, Msg::TipReady | Msg::TipPaused | Msg::TipUnavailable) {
                    assert!(text_with_key(l, *m, "Ctrl+Alt+Shift+Win+F10").chars().count() < 128);
                }
            }
        }
    }

    #[test]
    fn langid() {
        assert_eq!(Lang::from_langid(0x040D), Lang::He);
        assert_eq!(Lang::from_langid(0x040C), Lang::Fr);
        assert_eq!(Lang::from_langid(0x080C), Lang::Fr);
        assert_eq!(Lang::from_langid(0x0409), Lang::En);
        assert_eq!(Lang::from_langid(0x0419), Lang::En);
    }
}
